export function getCitiesForState(state: string): string[] {
  return Array.from(new Set(allTemples.filter((t) => t.state === state).map((t) => t.city))).sort();
}

export function getTempleCountForState(state: string): number {
  return allTemples.filter((t) => t.state === state).length;
}

