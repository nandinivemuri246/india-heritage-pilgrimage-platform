export const featuredTemples = featuredTempleIds
  .map((id) => allTemples.find((t) => t.id === id))
  .filter((t): t is Temple => t !== undefined);

export function getTempleById(id: string): Temple | undefined {
  return allTemples.find((t) => t.id === id);
}

export function getRelatedTemples(temple: Temple): Temple[] {
  return temple.relatedTempleIds
    .map((id) => getTempleById(id))
    .filter((t): t is Temple => t !== undefined);
}

export const allStates = Array.from(new Set(allTemples.map((t) => t.state))).sort();
